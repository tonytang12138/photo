const { spawn } = require('child_process');
const path = require('path');

console.log('? ??????????????????????...\n');

// ????????? localtunnel
const checkLocaltunnel = spawn('npm', ['list', 'localtunnel'], {
    cwd: __dirname,
    shell: true
});

checkLocaltunnel.on('close', (code) => {
    if (code !== 0) {
        console.log('? ?????? localtunnel...\n');
        const install = spawn('npm', ['install', 'localtunnel', '--save-dev'], {
            cwd: __dirname,
            shell: true,
            stdio: 'inherit'
        });

        install.on('close', () => {
            startTunnels();
        });
    } else {
        startTunnels();
    }
});

